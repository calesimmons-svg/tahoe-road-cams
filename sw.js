// Tahoe Road Cams — mobile app shell cache (v2)
const CACHE = 'tahoe-mobile-shell-v2';
const SHELL = [
  './mobile.html',
  './manifest.webmanifest',
  './icon-192.png',
  './icon-512.png',
  './icon-192-maskable.png',
  './icon-512-maskable.png',
  './apple-touch-icon.png'
];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(
    caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Only manage the app shell itself (same-origin). Live camera images, weather,
// traffic and chain-control data always go straight to the network so the
// page never shows stale conditions — this is purely so the shell (layout,
// icons, manifest) still opens if the phone is briefly offline.
self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  if (url.origin !== self.location.origin || e.request.method !== 'GET') return;
  if (!SHELL.some(p => url.pathname.endsWith(p.replace('./','/')))) return;

  e.respondWith(
    fetch(e.request).then(res => {
      const copy = res.clone();
      caches.open(CACHE).then(c => c.put(e.request, copy));
      return res;
    }).catch(() => caches.match(e.request))
  );
});
